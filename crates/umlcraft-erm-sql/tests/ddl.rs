//! SQL from the imported test schema: it reads again without a problem and gives the model
//! it came from (Dump → ER → SQL → ER).

mod support;

use pretty_assertions::assert_eq;
use support::{describe, fixtures, imported, rules, unordered};
use umlcraft_erm_sql::{Dialect, LeftOut, Options, ddl, read};

/// With `UMLCRAFT_DDL_OUT` set to a folder, the SQL a test writes goes there as
/// `{system}-{name}-{dialect}.sql`, to try it on a real server.
fn keep(system: &str, name: &str, dialect: Dialect, sql: &str) {
    if let Some(dir) = std::env::var_os("UMLCRAFT_DDL_OUT") {
        let file = std::path::Path::new(&dir).join(format!("{system}-{name}-{dialect:?}.sql"));
        std::fs::write(file, sql).unwrap();
    }
}

#[test]
fn the_sql_of_a_dump_gives_its_model_again() {
    for (system, name, dialect) in [
        ("mysql-9.7", "no-data", Dialect::MySql),
        ("mysql-8.4", "data", Dialect::MySql),
        ("mariadb-11.8", "routines", Dialect::MariaDb),
        ("postgres-17.6", "schema", Dialect::Postgres),
        ("postgres-16", "copy", Dialect::Postgres),
    ] {
        let path = fixtures().join("dumps").join(system).join(format!("{name}.sql"));
        let schema = read(&std::fs::read(path).unwrap(), None).unwrap();
        let (doc, result) = imported(&schema, &Options::default(), false);
        let model = doc.model();
        let named = umlcraft_erm_sql::imported_dialect(model, result.diagram);
        assert_eq!(named, Some(dialect), "{system}");
        let out = ddl(model, result.diagram, dialect).unwrap();
        keep(system, name, dialect, &out.sql);
        assert_eq!(out.left_out, [], "{system}");
        let again = read(out.sql.as_bytes(), Some(dialect)).unwrap();
        assert_eq!(again.problems, [], "{system}\n{}", out.sql);
        assert_eq!(again.tables.len(), schema.tables.len(), "{system}");
        let (doc2, result2) = imported(&again, &Options::default(), false);
        assert_eq!(
            unordered(&describe(doc2.model(), result2.package)),
            unordered(&describe(model, result.package)),
            "{system}\n{}",
            out.sql
        );
        // Types, conditions, uniqueness, indexes and domains come back as well.
        assert_eq!(
            rules(doc2.model(), result2.package),
            rules(model, result.package),
            "{system}\n{}",
            out.sql
        );
    }
}

/// The columns, keys and defaults of `tests/fixtures/export` (a mysqldump of MySQL 9.7 and a
/// schema in the form of pg_dump 16) that servers refuse unless the SQL takes care: written
/// for both dialects, they read again without a problem and look as both servers take them.
/// (The CI job "SQL on real servers" loads them into MySQL 8 and PostgreSQL 16.)
#[test]
fn the_export_cases_give_sql_the_servers_take() {
    // `dropped`: the columns (`table.column`) whose default, or part of it, the dialect has
    // nothing for; they are reported, nothing else is.
    let sql_of = |file: &str, to: Dialect, dropped: &[&str]| {
        let path = fixtures().join("export").join(file);
        let schema = read(&std::fs::read(path).unwrap(), None).unwrap();
        // A comment on a view's column is no problem.
        assert_eq!(schema.problems, [], "{file}");
        let (doc, result) = imported(&schema, &Options::default(), false);
        let out = ddl(doc.model(), result.diagram, to).unwrap();
        keep("export", file.trim_end_matches(".sql"), to, &out.sql);
        let reported: Vec<String> = out
            .left_out
            .iter()
            .map(|l| match l {
                LeftOut::Default { table, column, .. } => format!("{table}.{column}"),
                other => panic!("{file} {to:?}: {other:?}"),
            })
            .collect();
        assert_eq!(reported, dropped, "{file} {to:?}: {:?}", out.left_out);
        let again = read(out.sql.as_bytes(), Some(to)).unwrap();
        assert_eq!(again.problems, [], "{file} {to:?}\n{}", out.sql);
        out.sql
    };
    let has = |sql: &str, lines: &[&str]| {
        for line in lines {
            assert!(sql.contains(line), "{line}\n{sql}");
        }
    };
    let pg = sql_of("mysql.sql", Dialect::Postgres, &["user.seen", "user.updated", "user.changed"]);
    has(
        &pg,
        &[
            // An identity column is an integer, and the columns that reference it alike.
            "\n  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,",
            "\n  user_id bigint NOT NULL,",
            // tinyint(1) is boolean, and so are its defaults.
            "\n  active boolean NOT NULL DEFAULT FALSE,",
            "\n  read boolean NOT NULL DEFAULT TRUE,",
            // Strings stay strings, whatever they look like.
            "\n  note varchar(40) DEFAULT '(none)',",
            "\n  code varchar(10) DEFAULT '007',",
            "\n  word varchar(10) DEFAULT 'NULL',",
            "\n  blank varchar(10) DEFAULT ' ',",
            "\n  nothing varchar(10) NOT NULL DEFAULT '',",
            r"  path varchar(40) DEFAULT 'C:\temp',",
            // MySQL's expressions as PostgreSQL has them, no zero date, no ON UPDATE.
            "\n  token char(36) DEFAULT gen_random_uuid(),",
            "\n  label varchar(20) DEFAULT 'x',",
            "\n  born date DEFAULT CURRENT_DATE,",
            "\n  seen timestamp NOT NULL,",
            "\n  updated timestamp,",
            "\n  changed timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),",
            "\n  flags bit(1) DEFAULT b'0',",
            "\n  CHECK (gender in ('MALE','FEMALE'))",
            // PostgreSQL's reserved words in quotes, MySQL's other ones not.
            "CREATE TABLE \"user\" (",
            "\n  \"left\" integer,",
            "\n  values integer,",
            "\n  \"order\" integer NOT NULL DEFAULT 0,",
            // An index named like a table gets another name; prefix lengths go.
            "CREATE INDEX tag2 ON \"user\" (rank);",
            "CREATE INDEX body_start ON \"user\" (body);",
            "CREATE UNIQUE INDEX uq_user_summary ON \"user\" (summary);",
        ],
    );
    let my = sql_of("mysql.sql", Dialect::MySql, &["user.seen"]);
    has(
        &my,
        &[
            "\n  `read` tinyint(1) NOT NULL DEFAULT 1,",
            "\n  `values` int,",
            "\n  code varchar(10) DEFAULT '007',",
            "\n  token char(36) DEFAULT (uuid()),",
            "\n  changed datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE \
             CURRENT_TIMESTAMP(3),",
            "\n  updated timestamp ON UPDATE CURRENT_TIMESTAMP,",
            // MySQL 8's strict mode refuses the zero date.
            "\n  seen datetime NOT NULL,",
            "CREATE INDEX body_start ON user (body(100));",
            "CREATE INDEX tag ON user (`rank`);",
            "CREATE UNIQUE INDEX uq_user_summary ON user (summary(50));",
        ],
    );
    let my = sql_of("postgres.sql", Dialect::MySql, &["account.tags", "account.valid_until"]);
    has(
        &my,
        &[
            // MySQL keys text only by a prefix.
            "\n  email varchar(255) NOT NULL UNIQUE,",
            "\n  token varchar(255) NOT NULL,",
            "CREATE INDEX account_nick_idx ON account (nick(255));",
            // Literal defaults of text and JSON in parentheses; what MySQL has no value for
            // goes.
            "\n  nick text NOT NULL DEFAULT (''),",
            "\n  data json NOT NULL DEFAULT ('{}'),",
            "\n  tags json,",
            "\n  valid_until datetime,",
            "\n  marker varchar(10) DEFAULT 'a::b',",
            "\n  uid char(36) NOT NULL DEFAULT (uuid()),",
            "\n  created_at datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),",
            "\n  born date DEFAULT (CURRENT_DATE),",
            "\n  `offset` int,",
            "\n  `Rank` int,",
            // Conditions with strings that hold `E'`, `~` or `::` stay.
            "\n  CHECK ((gender) IN ('MALE', 'FEMALE')),",
            "\n  CHECK ((status) IN ('ACTIVE', 'NONE', 'TRUE')),",
            "\n  CHECK ((marker) <> 'x~y')",
        ],
    );
    // MySQL indexes no JSON.
    assert!(!my.contains("account_data_idx"), "{my}");
    let pg = sql_of("postgres.sql", Dialect::Postgres, &[]);
    has(
        &pg,
        &[
            "\n  tags text[] DEFAULT ARRAY[]::text[],",
            "\n  valid_until timestamp without time zone DEFAULT 'infinity',",
            "\n  code character varying(10) DEFAULT '007',",
            "\n  nick text NOT NULL DEFAULT '',",
            "\n  \"offset\" integer,",
        ],
    );
}

/// A dump of one dialect written for the other reads there without a problem and gives the
/// same tables, keys and relationships; generated columns become plain ones.
#[test]
fn the_sql_for_the_other_dialect_gives_the_same_model() {
    for (system, name, to) in [
        ("postgres-17.6", "schema", Dialect::MySql),
        ("mysql-9.7", "no-data", Dialect::Postgres),
        ("mariadb-11.8", "no-data", Dialect::Postgres),
    ] {
        let path = fixtures().join("dumps").join(system).join(format!("{name}.sql"));
        let schema = read(&std::fs::read(path).unwrap(), None).unwrap();
        let (doc, result) = imported(&schema, &Options::default(), false);
        let model = doc.model();
        let out = ddl(model, result.diagram, to).unwrap();
        keep(system, name, to, &out.sql);
        let generated = LeftOut::Generated { table: "flug".into(), column: "dauer_min".into() };
        assert_eq!(out.left_out, [generated], "{system}");
        let again = read(out.sql.as_bytes(), Some(to)).unwrap();
        assert_eq!(again.problems, [], "{system}\n{}", out.sql);
        assert_eq!(again.tables.len(), schema.tables.len(), "{system}");
        let (doc2, result2) = imported(&again, &Options::default(), false);
        // A schema of PostgreSQL is part of the table's name in MySQL, which capitalizes it.
        let plain = |t: String| t.replace(" (abgeleitet)", "").replace("Fracht.", "fracht.");
        assert_eq!(
            unordered(&plain(describe(doc2.model(), result2.package))),
            unordered(&plain(describe(model, result.package))),
            "{system}\n{}",
            out.sql
        );
    }
}

#[test]
fn moved_to_the_other_dialect_names_types_and_numbers_stay_apart() {
    // MySQL enumerations become PostgreSQL types named after table and column, which may meet.
    let sql = "CREATE TABLE `order` (id int NOT NULL, status_type enum('a','b'), \
               PRIMARY KEY (id));\n\
               CREATE TABLE order_status (id int NOT NULL, type enum('x','y'), \
               PRIMARY KEY (id));";
    let schema = read(sql.as_bytes(), Some(Dialect::MySql)).unwrap();
    let (doc, result) = imported(&schema, &Options::default(), false);
    let out = ddl(doc.model(), result.diagram, Dialect::Postgres).unwrap();
    assert!(out.sql.contains("CREATE TYPE order_status_type AS ENUM ('a', 'b');"), "{}", out.sql);
    assert!(out.sql.contains("CREATE TYPE order_status_type_2 AS ENUM ('x', 'y');"), "{}", out.sql);
    let again = read(out.sql.as_bytes(), Some(Dialect::Postgres)).unwrap();
    assert_eq!(again.problems, [], "{}", out.sql);

    // PostgreSQL: a domain in a schema of its own, and a numeric without precision.
    let sql = "CREATE SCHEMA common;\n\
               CREATE DOMAIN common.email AS text;\n\
               CREATE TABLE public.person (id integer NOT NULL, mail common.email, \
               balance numeric, CONSTRAINT person_pkey PRIMARY KEY (id));";
    let schema = read(sql.as_bytes(), Some(Dialect::Postgres)).unwrap();
    let (doc, result) = imported(&schema, &Options::default(), false);
    let out = ddl(doc.model(), result.diagram, Dialect::Postgres).unwrap();
    let schema_at = out.sql.find("CREATE SCHEMA IF NOT EXISTS common;");
    let domain_at = out.sql.find("CREATE DOMAIN common.email");
    assert!(schema_at.is_some() && schema_at < domain_at, "{}", out.sql);
    let out = ddl(doc.model(), result.diagram, Dialect::MySql).unwrap();
    assert!(out.sql.contains("balance decimal(65,30)"), "{}", out.sql);
}
